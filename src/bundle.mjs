import { spawn } from 'node:child_process';
import { zipSync, strToU8 } from 'fflate';
import { validateFiles } from './contracts.mjs';

/** Add the configured student attribution to every generated source file. */
function attribute(file, config) {
  const identity = `Author: ${config.studentName} | Student ID: ${config.studentId}`
    .replace(/[\r\n]/g, ' ').replace(/\*\//g, '').replace(/--/g, '');
  let prefix = '';
  if (/\.(m?js|css)$/i.test(file.path)) prefix = `/* ${identity} */\n`;
  if (/\.(html|svg)$/i.test(file.path)) prefix = `<!-- ${identity} -->\n`;
  return { ...file, content: prefix + file.content };
}

/** Syntax-check generated JavaScript without executing any of its code. */
export async function checkJavaScript(files) {
  for (const file of files.filter(item => /\.m?js$/i.test(item.path))) {
    await new Promise((resolve, reject) => {
      const child = spawn(process.execPath, ['--check', '--input-type=module'], {
        stdio: ['pipe', 'ignore', 'pipe'], windowsHide: true,
      });
      let diagnostic = '';
      const timer = setTimeout(() => child.kill(), 10000);
      child.stderr.on('data', chunk => { diagnostic += chunk.toString().slice(0, 3000); });
      child.on('error', reject);
      child.on('close', code => {
        clearTimeout(timer);
        if (code === 0) resolve();
        else reject(new Error(`Generated JavaScript has invalid syntax in ${file.path}: ${diagnostic.slice(0, 1000)}`));
      });
      child.stdin.on('error', () => {}); // A parser may close stdin immediately on invalid input.
      child.stdin.end(file.content);
    });
  }
}

/** Assemble generated files with deterministic run instructions and honest verification status. */
export function buildBundle(run, applicationFiles, testFiles, config) {
  const files = [...applicationFiles, ...testFiles].map(file => attribute(file, config));
  files.push({
    path: 'package.json',
    content: JSON.stringify({
      name: 'generated-application', version: '1.0.0', private: true, type: 'module',
      engines: { node: '>=22' },
      scripts: { start: 'node server.mjs', test: 'node --test tests/*.test.mjs' },
    }, null, 2) + '\n',
  });
  files.push({ path: 'requirements.json', content: JSON.stringify({ ...run.request, plan: run.plan }, null, 2) + '\n' });
  files.push({
    path: 'generation-report.json',
    content: JSON.stringify({
      runId: run.id, model: run.model, usage: run.usage,
      agents: run.stages.map(({ name, tool, usage }) => ({ name, tool, usage })),
      javascriptSyntax: 'passed', testsExecuted: false,
    }, null, 2) + '\n',
  });
  files.push({ path: 'README.md', content: `# Generated application\n\n${run.plan.name}\n\n` +
    `## Run\n\nRequires Node.js 22 or newer. No dependency installation is needed.\n\n` +
    '```sh\nnode server.mjs\n```\n\nOpen http://127.0.0.1:3100 (or the PORT you configured).\n\n' +
    '## Test\n\n```sh\nnode --test tests/*.test.mjs\n```\n\n' +
    'JavaScript syntax was checked during generation. The generated tests have NOT been executed by the AI Coder. Run them before relying on the output.\n\n' +
    'See requirements.json for the original requirements and plan, and generation-report.json for actual API/token usage.\n\n' +
    'This project was generated by an LLM. Review its behavior and use fictional symptom data for demonstrations.\n' });
  return validateFiles(files);
}

/** Package only validated relative files; never create entries outside the ZIP root. */
export function zipBundle(files) {
  validateFiles(files);
  const entries = Object.create(null);
  for (const file of files) entries[file.path] = strToU8(file.content);
  return zipSync(entries, { level: 6 });
}
